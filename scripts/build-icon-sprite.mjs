import { createRequire } from "node:module";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const require = createRequire(new URL("frontend/package.json", root));
const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const {
  spriteIconArtwork: iconArtwork,
} = require("./components/Icons/spriteIconArtwork.tsx");
const {
  spriteIconNames: iconNames,
  closeViewBoxSize,
} = require("./components/Icons/iconMetadata.ts");
const {
  categoryIconViewBoxes,
} = require("./components/Icons/categoryIconViewBoxes.ts");

const symbols = iconNames.flatMap((name) =>
  [24, 36, 48].map((size) => {
    const dimension = name === "close" ? closeViewBoxSize[size] : size;
    const id = `${name}-${size}`;
    return React.createElement(
      "g",
      {
        key: id,
        id,
        "data-view-box":
          categoryIconViewBoxes[name]?.[size] ??
          `0 0 ${dimension} ${dimension}`,
        fill: "none",
      },
      iconArtwork[name][size](`fs-${id}`),
    );
  }),
);
const contents =
  "<!-- Generated by scripts/build-icon-sprite.mjs; edit spriteIconArtwork.tsx. -->\n" +
  renderToStaticMarkup(
    React.createElement(
      "svg",
      { xmlns: "http://www.w3.org/2000/svg" },
      symbols,
    ),
  ) +
  "\n";
const output = new URL("frontend/public/svg/icons/sprite.svg", root);
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8")) !== contents)
    throw new Error("Icon sprite is stale. Run pnpm build:icons.");
} else await writeFile(output, contents);
console.log(
  `Icon sprite ${process.argv.includes("--check") ? "verified" : "generated"}: ${fileURLToPath(output)}`,
);
