import { build, context } from "esbuild";
import { format } from "prettier";
import { mkdir, readFile, rename, unlink, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const defaultEntry = resolve(
  root,
  "frontend/infrastructure/theme/themeBootstrap.ts",
);
const defaultOutput = resolve(root, "frontend/generated/theme-bootstrap.ts");

function options(entry) {
  return {
    entryPoints: [entry],
    bundle: true,
    write: false,
    platform: "browser",
    format: "iife",
    target: "es2017",
    charset: "ascii",
    minify: true,
    legalComments: "none",
    define: { __THEME_BOOTSTRAP_ENTRY__: "true" },
    logLevel: "silent",
  };
}

async function artifact(result) {
  // esbuild escapes closing script tags in the executable payload. This second
  // serialization layer stores that payload as data in a TypeScript module.
  const literal = JSON.stringify(result.outputFiles[0].text).replace(
    /[<>&\u2028\u2029]/g,
    (character) =>
      `\\u${character.charCodeAt(0).toString(16).padStart(4, "0")}`,
  );
  return format(
    `// Generated by scripts/build-theme-bootstrap.mjs. Do not edit.\nexport const themeBootstrapScript = ${literal};\n`,
    { parser: "typescript" },
  );
}

async function publish(output, contents, check) {
  let previous;
  try {
    previous = await readFile(output, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (previous === contents) return;
  if (check)
    throw new Error(
      "Theme bootstrap is missing or stale. Run pnpm build:theme-bootstrap and review the generated diff.",
    );
  await mkdir(dirname(output), { recursive: true });
  const temporary = `${output}.${process.pid}.tmp`;
  try {
    await writeFile(temporary, contents, { flag: "wx" });
    await rename(temporary, output);
  } finally {
    await unlink(temporary).catch((error) => {
      if (error.code !== "ENOENT") throw error;
    });
  }
}

export async function generate({
  entry = defaultEntry,
  output = defaultOutput,
  check = false,
} = {}) {
  const result = await build(options(entry));
  await publish(output, await artifact(result), check);
}

export async function watch({
  entry = defaultEntry,
  output = defaultOutput,
  onBuild = () => {},
} = {}) {
  const compiler = await context({
    ...options(entry),
    plugins: [
      {
        name: "theme-artifact",
        setup(compilerBuild) {
          compilerBuild.onEnd(async (result) => {
            try {
              if (result.errors.length)
                throw new Error(
                  result.errors.map((error) => error.text).join("\n"),
                );
              await publish(output, await artifact(result), false);
              onBuild(null);
            } catch (error) {
              onBuild(error);
            }
          });
        },
      },
    ],
  });
  await compiler.watch();
  return () => compiler.dispose();
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  const args = process.argv.slice(2);
  try {
    if (
      args.length > 1 ||
      args.some((arg) => !["--check", "--watch"].includes(arg))
    ) {
      throw new Error(
        "Usage: node scripts/build-theme-bootstrap.mjs [--check|--watch]",
      );
    }
    if (args[0] === "--watch") {
      const dispose = await watch({
        onBuild: (error) => {
          if (error)
            console.error(`Theme bootstrap build failed: ${error.message}`);
          else
            console.log(
              "Theme bootstrap ready (watching entry and imported sources).",
            );
        },
      });
      for (const signal of ["SIGINT", "SIGTERM"])
        process.once(signal, async () => {
          await dispose();
          process.exit(0);
        });
    } else {
      await generate({ check: args[0] === "--check" });
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
